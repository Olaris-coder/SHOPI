create table if not exists public.products (
 id bigint generated by default as identity primary key,
 name text not null, description text,
 price numeric(12,2) not null check(price >= 0),
 is_active boolean not null default true,
 created_at timestamptz not null default now()
);
create table if not exists public.orders (
 id bigint generated by default as identity primary key,
 customer_name text not null, customer_email text not null,
 customer_phone text, total numeric(12,2) not null,
 status text not null default 'Pending',
 created_at timestamptz not null default now()
);
create table if not exists public.order_items (
 id bigint generated by default as identity primary key,
 order_id bigint not null references public.orders(id) on delete cascade,
 product_id bigint not null references public.products(id),
 product_name text not null, quantity integer not null check(quantity > 0),
 unit_price numeric(12,2) not null, line_total numeric(12,2) not null
);
